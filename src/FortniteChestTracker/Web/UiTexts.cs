    private static readonly Dictionary<string, string> Cache = new();

    /// <summary>All the texts in one language, as a JSON object (null for an unknown language).</summary>
    public static string? Json(string lang)
    {
        var code = L.Normalize(lang);
        if (code == null)
        {
            return null;
        }
        lock (Cache)
        {
            if (!Cache.TryGetValue(code, out var json))
            {
                var dict = All.ToDictionary(x => x.Key, x => code switch { "en" => x.En, "es" => x.Es, _ => x.Fr });
                json = JsonSerializer.Serialize(dict);
                Cache[code] = json;
            }
            return json;
        }
    }

    /// <summary>One text in the language of the tool (the key itself when unknown). Used by the overlay.</summary>
    public static string Get(string key)
    {
        foreach (var x in All)
        {
            if (x.Key == key)
            {
                return L.Code switch { "en" => x.En, "es" => x.Es, _ => x.Fr };
            }
        }
        return key;
    }

    /// <summary>Keys (tests: every key used by the page must exist).</summary>
    public static IEnumerable<string> Keys => All.Select(x => x.Key);
